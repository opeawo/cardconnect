import { build as esbuild } from "esbuild";
import { build as viteBuild } from "vite";
import { rm, readFile } from "node:fs/promises";

// server deps to bundle to reduce openat(2) syscalls
// which helps cold start times
const allowlist = [
  "@google/generative-ai",
  "axios",
  "cors",
  "date-fns",
  "drizzle-orm",
  "drizzle-zod",
  "express",
  "express-rate-limit",
  "express-session",
  "jsonwebtoken",
  "memorystore",
  "multer",
  "nanoid",
  "nodemailer",
  "openai",
  "passport",
  "passport-local",
  "stripe",
  "uuid",
  "ws",
  "xlsx",
  "zod",
  "zod-validation-error",
];

async function buildAll() {
  await rm("dist", { recursive: true, force: true });

  console.log("generating PWA icons...");
  // Run the icon generator as a child process so its sharp imports stay out
  // of the build script's import graph (and so failures don't block builds
  // when the script changes — fail loudly only when artwork is missing).
  const { spawnSync } = await import("node:child_process");
  const iconRun = spawnSync("node", ["scripts/gen-pwa-icons.mjs"], {
    stdio: "inherit",
  });
  if (iconRun.status !== 0) {
    throw new Error("PWA icon generation failed");
  }

  console.log("building client...");
  await viteBuild();

  console.log("building server...");
  const pkg = JSON.parse(await readFile("package.json", "utf-8"));
  const allDeps = [
    ...Object.keys(pkg.dependencies || {}),
    ...Object.keys(pkg.devDependencies || {}),
  ];
  const externals = allDeps.filter((dep) => !allowlist.includes(dep));

  await esbuild({
    entryPoints: ["server/index.ts"],
    platform: "node",
    bundle: true,
    format: "cjs",
    outfile: "dist/index.cjs",
    define: {
      "process.env.NODE_ENV": '"production"',
      // DEEPSEEK_API_KEY is intentionally NOT inlined here. It's read at
      // runtime via process.env so the same bundle is safe to commit and
      // deploy to any host (Render, Fly, etc.) where secrets are injected
      // as environment variables.
    },
    minify: true,
    external: externals,
    logLevel: "info",
  });
}

buildAll().catch((err) => {
  console.error(err);
  process.exit(1);
});
